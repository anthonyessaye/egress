package app.egress.ui.components

import android.content.Context
import androidx.compose.ui.graphics.Path
import java.io.DataInputStream

/**
 * Equirectangular map space: x = lon + 180 (0..360), y = TOP_LAT - lat (0..HEIGHT). One unit = one degree.
 * The map is cropped to 82.5°N … 57°S: nothing lives further south than Tierra del Fuego except Antarctica.
 */
object MapSpace {
    const val WIDTH = 360f
    const val TOP_LAT = 82.5f
    const val BOTTOM_LAT = -57f
    const val HEIGHT = TOP_LAT - BOTTOM_LAT

    fun x(lon: Double): Float = lon.toFloat() + 180f
    fun y(lat: Double): Float = TOP_LAT - lat.toFloat().coerceIn(BOTTOM_LAT, TOP_LAT)
}

/** One Natural Earth admin-0 feature. Some ISO codes have several (e.g. Australia + its island territories). */
class CountryShape(
    val cc: String,
    val name: String,
    /** Natural Earth's preferred label anchor, in map space. */
    val labelX: Float,
    val labelY: Float,
    /** Natural Earth LABELRANK: 0-2 big/important … 9 tiny. */
    val rank: Int,
    val path: Path,
    /** Width of the largest ring's bounding box, in degrees: decides whether a label fits. */
    val mainWidth: Float,
    /** Rough area in square degrees, used to prioritise labels. */
    val area: Float,
)

class CountryShapes(val countries: List<CountryShape>, val land: Path) {
    val byCc: Map<String, List<CountryShape>> = countries.groupBy { it.cc }

    companion object {
        @Volatile private var cached: CountryShapes? = null

        fun peek(): CountryShapes? = cached

        /**
         * Reads assets/countries.bin (generated by tools/build_countries.py from Natural Earth 1:50m, public domain).
         * ~30k points; parses in a few ms. Call off the main thread.
         */
        fun load(context: Context): CountryShapes {
            cached?.let { return it }
            synchronized(this) {
                cached?.let { return it }
                val loaded = context.assets.open("countries.bin").use { raw ->
                    val input = DataInputStream(raw.buffered())
                    val magic = ByteArray(4).also { input.readFully(it) }
                    check(String(magic, Charsets.US_ASCII) == "EGC1") { "bad countries.bin" }
                    val n = input.readUnsignedShort()
                    val land = Path()
                    val list = ArrayList<CountryShape>(n)
                    repeat(n) {
                        val cc = String(byteArrayOf(input.readByte(), input.readByte()), Charsets.US_ASCII)
                        val name = ByteArray(input.readUnsignedShort()).also { input.readFully(it) }.toString(Charsets.UTF_8)
                        val lx = input.readShort() / 100f + 180f
                        val ly = MapSpace.TOP_LAT - input.readShort() / 100f
                        val rank = input.readUnsignedByte()
                        val path = Path()
                        var mainWidth = 0f
                        var mainArea = -1f
                        var total = 0f
                        repeat(input.readUnsignedShort()) {
                            val k = input.readUnsignedShort()
                            var minX = Float.MAX_VALUE
                            var maxX = -Float.MAX_VALUE
                            var a = 0f
                            var px = 0f
                            var py = 0f
                            for (i in 0 until k) {
                                val x = input.readShort() / 100f + 180f
                                val y = MapSpace.TOP_LAT - input.readShort() / 100f
                                if (i == 0) path.moveTo(x, y) else {
                                    path.lineTo(x, y)
                                    a += px * y - x * py
                                }
                                px = x; py = y
                                if (x < minX) minX = x
                                if (x > maxX) maxX = x
                            }
                            path.close()
                            val ringArea = kotlin.math.abs(a) / 2f
                            total += ringArea
                            if (ringArea > mainArea) { mainArea = ringArea; mainWidth = maxX - minX }
                        }
                        land.addPath(path)
                        list += CountryShape(cc, name, lx, ly, rank, path, mainWidth, total)
                    }
                    CountryShapes(list, land)
                }
                cached = loaded
                return loaded
            }
        }
    }
}
